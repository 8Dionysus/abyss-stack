// Last-resort presentation guard for source-owned draft labels that have no
// reviewed English equivalent yet. This is deliberately transliteration, not
// a source mutation: it keeps proper names and unresolved wording legible in
// an English graph while guaranteeing that a public EN surface never mixes
// Cyrillic into its chrome, labels, routes, or tooltips.
